"""Running bwrap: signal forwarding and exit status (FR-23, FR-24, FR-24a)."""

import json
import os
import signal
from collections.abc import Mapping, Sequence
from dataclasses import dataclass, field

from agent_sandbox.errors import SetupError

FORWARDED_SIGNALS = (signal.SIGINT, signal.SIGTERM, signal.SIGHUP)

# Python ignores these; the child must start with the default action (as subprocess does).
_RESET_SIGNALS = (signal.SIGPIPE, signal.SIGXFSZ)


@dataclass
class BwrapStatus:
    """What bwrap reports on ``--json-status-fd``: the sandbox's init and the exit code."""

    init_pid: int | None = None
    exit_code: int | None = None
    _buffer: bytes = field(default=b"", repr=False)

    def feed(self, data: bytes) -> None:
        """Parse complete JSON lines from ``data``; the first ``child-pid`` wins."""
        self._buffer += data
        *lines, self._buffer = self._buffer.split(b"\n")
        for line in lines:
            try:
                report = json.loads(line)
            except ValueError:
                continue
            if not isinstance(report, dict):
                continue
            if self.init_pid is None and isinstance(report.get("child-pid"), int):
                self.init_pid = report["child-pid"]
            if isinstance(report.get("exit-code"), int):
                self.exit_code = report["exit-code"]


def exit_status(wait_status: int, status: BwrapStatus) -> int:
    """Map bwrap's wait status and its JSON report to the exit code of ``run`` (FR-24a)."""
    if status.exit_code is not None:
        return status.exit_code
    code = os.waitstatus_to_exitcode(wait_status)
    if code < 0:
        return 128 - code
    if code == 0:
        return 0
    hint = "" if status.init_pid else "; are unprivileged user namespaces available?"
    raise SetupError(f"bwrap could not set up the sandbox (see its message above){hint}")


def program_pid(init_pid: int, proc: str = "/proc") -> int | None:
    """Return the program's pid: the first child of the sandbox's init process."""
    try:
        with open(f"{proc}/{init_pid}/task/{init_pid}/children", encoding="ascii") as file:
            children = file.read().split()
    except OSError:
        return None
    return int(children[0]) if children else None


def _read_available(fd: int, status: BwrapStatus) -> None:
    while True:
        try:
            data = os.read(fd, 4096)
        except BlockingIOError:
            return
        if not data:
            return
        status.feed(data)


def _forward(signum: int, bwrap_pid: int, status: BwrapStatus) -> None:
    target = program_pid(status.init_pid) if status.init_pid else None
    try:
        os.kill(target or bwrap_pid, signum)
    except ProcessLookupError:
        pass


def supervise(command: Sequence[str], env: Mapping[str, str]) -> int:
    """Run ``command`` (bwrap with an absolute path), wait for it, return the exit code.

    Signals are waited for synchronously, so their origin is known: signals sent by
    another process are forwarded to the program, signals generated by the terminal are
    not, because the terminal already sent them to the program (FR-24).
    """
    status = BwrapStatus()
    status_read, status_write = os.pipe()
    os.set_blocking(status_read, False)
    os.set_inheritable(status_write, True)
    argv = [command[0], "--json-status-fd", str(status_write), *command[1:]]
    waited = {*FORWARDED_SIGNALS, signal.SIGCHLD}
    old_mask = signal.pthread_sigmask(signal.SIG_BLOCK, waited)
    try:
        try:
            pid = os.posix_spawn(argv[0], argv, env, setsigmask=(), setsigdef=_RESET_SIGNALS)
        except OSError as exc:
            raise SetupError(f"cannot start {argv[0]}: {exc.strerror}") from exc
        finally:
            os.close(status_write)
        while True:
            info = signal.sigwaitinfo(waited)
            if info.si_signo == signal.SIGCHLD:
                done, wait_status = os.waitpid(pid, os.WNOHANG)
                if done:
                    break
            elif info.si_code <= 0:  # sent by a process (SI_USER, SI_QUEUE, SI_TKILL, ...)
                _read_available(status_read, status)
                _forward(info.si_signo, pid, status)
        _read_available(status_read, status)
        return exit_status(wait_status, status)
    finally:
        os.close(status_read)
        signal.pthread_sigmask(signal.SIG_SETMASK, old_mask)
